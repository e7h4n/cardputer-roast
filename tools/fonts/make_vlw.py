#!/usr/bin/env python3
"""Generate the anti-aliased VLW fonts the Roast UI uses, as C arrays.

    python3 tools/fonts/make_vlw.py      # writes main/apps/app_roast/fonts/roast_fonts_data.h

Source font: Space Grotesk (SIL OFL 1.1, see OFL.txt next to this script), variable weight axis.
VLW is the Processing smooth-font format that M5GFX/LovyanGFX draws with 8-bit alpha:
  header  6 x int32 BE: glyph count, version 11, size, 0, ascent, descent
  glyphs  7 x int32 BE each, sorted by code point: unicode, height, width, xAdvance, dY (top above baseline), dX, 0
  bitmaps width*height alpha bytes per glyph, same order
The space character is deliberately left out: LovyanGFX always draws a space with its own width, and leaving it
out makes textWidth() use that same width, so measured and drawn text agree.
"""
import os
import struct
import sys

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
TTF = os.path.join(HERE, 'SpaceGrotesk-wght.ttf')
OUT = os.path.join(HERE, '..', '..', 'main', 'apps', 'app_roast', 'fonts', 'roast_fonts_data.h')

ASCII = ''.join(chr(c) for c in range(0x21, 0x7F))
EXTRA = '°±·×–…‹›←↑→↓↗↘−'
DIGITS = '0123456789.-+:%°'

# name, pixel size, weight, glyphs. Sizes match the approved 240x135 mock-ups.
FONTS = [
    ('SG10', 10, 'Medium', ASCII + EXTRA),   # key labels, captions
    ('SG11', 11, 'Medium', ASCII + EXTRA),   # secondary text
    ('SG12B', 12, 'Bold', ASCII + EXTRA),    # row labels
    ('SG14', 14, 'Medium', ASCII + EXTRA),   # values, titles
    ('SG16B', 16, 'Bold', ASCII + EXTRA),    # page titles, emphasised values
    ('SG19B', 19, 'Bold', ASCII + EXTRA),    # card values
    ('SG23B', 23, 'Bold', DIGITS),           # roast clock
    ('SG47B', 47, 'Bold', DIGITS),           # hero temperature
]


def vlw(size, weight, chars):
    f = ImageFont.truetype(TTF, size, layout_engine=ImageFont.Layout.BASIC)
    f.set_variation_by_name(weight)
    ascent, descent = f.getmetrics()
    heads, bitmaps = [], []
    for ch in sorted(set(chars), key=ord):
        l, t, r, b = f.getbbox(ch, anchor='ls')
        w, h = max(0, r - l), max(0, b - t)
        adv = int(round(f.getlength(ch)))
        im = Image.new('L', (max(1, w), max(1, h)), 0)
        if w and h:
            ImageDraw.Draw(im).text((-l, -t), ch, font=f, fill=255, anchor='ls')
        data = im.tobytes() if w and h else b''
        assert 0 <= w < 256 and 0 <= adv < 256 and -128 <= l < 128, (ch, w, adv, l)
        heads.append(struct.pack('>7i', ord(ch), h, w, adv, -t, l, 0))
        bitmaps.append(data)
    blob = struct.pack('>6i', len(heads), 11, size, 0, ascent, descent) + b''.join(heads) + b''.join(bitmaps)
    return blob, len(heads)


def main():
    out = ['// Generated by tools/fonts/make_vlw.py from Space Grotesk (SIL OFL 1.1). Do not edit.',
           '#pragma once', '#include <cstdint>', '']
    total = 0
    for name, size, weight, chars in FONTS:
        blob, n = vlw(size, weight, chars)
        total += len(blob)
        out.append(f'// {name}: {size}px {weight}, {n} glyphs, {len(blob)} bytes')
        out.append(f'static const uint8_t kFont{name}[] = {{')
        for i in range(0, len(blob), 24):
            out.append('    ' + ', '.join(f'0x{x:02x}' for x in blob[i:i + 24]) + ',')
        out.append('};')
        out.append('')
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, 'w').write('\n'.join(out))
    print(f'wrote {os.path.relpath(OUT)}: {len(FONTS)} fonts, {total} bytes', file=sys.stderr)


if __name__ == '__main__':
    main()
